import React, { useState, useMemo } from 'react'
import type { Ticket, TicketStatus } from '../types/ticket'
import { Search, CheckCircle2, XCircle, Printer, Inbox, Download } from 'lucide-react'

interface TicketListProps {
  tickets: Ticket[]
  onVerifyTicket: (ticketId: string) => void
  onRevokeTicket: (ticketId: string) => void
  onPrintTicket: (ticket: Ticket) => void
}

export const TicketList: React.FC<TicketListProps> = ({
  tickets,
  onVerifyTicket,
  onRevokeTicket,
  onPrintTicket,
}) => {
  const [searchTerm, setSearchTerm] = useState('')
  const [statusFilter, setStatusFilter] = useState<'ALL' | TicketStatus>('ALL')

  const filteredTickets = useMemo(() => {
    return tickets.filter((t) => {
      const matchesSearch =
        t.attendeeName.toLowerCase().includes(searchTerm.toLowerCase()) ||
        t.attendeeEmail.toLowerCase().includes(searchTerm.toLowerCase()) ||
        t.ticketNumber.toLowerCase().includes(searchTerm.toLowerCase())

      const matchesStatus = statusFilter === 'ALL' || t.status === statusFilter

      return matchesSearch && matchesStatus
    })
  }, [tickets, searchTerm, statusFilter])

  return (
    <section aria-labelledby="ticket-registry-heading" className="space-y-6">
      <div className="flex flex-col md:flex-row items-start md:items-center justify-between gap-4 pb-4 border-b border-zinc-800">
        <div>
          <h2 id="ticket-registry-heading" className="text-lg font-semibold text-zinc-100 tracking-tight">
            Issued Ticket Registry ({filteredTickets.length})
          </h2>
          <p className="text-xs text-zinc-400">
            Real-time feed of digital passes generated by floor operators.
          </p>
        </div>

        {/* Filter controls */}
        <div className="flex flex-col sm:flex-row items-stretch sm:items-center gap-3 w-full md:w-auto">
          <div className="relative min-w-[220px]">
            <Search className="w-4 h-4 absolute left-3 top-1/2 -translate-y-1/2 text-zinc-400 pointer-events-none" aria-hidden="true" />
            <input
              type="text"
              id="ticket-search"
              aria-label="Search tickets"
              placeholder="Search by name, email, or #..."
              value={searchTerm}
              onChange={(e) => setSearchTerm(e.target.value)}
              className="w-full pl-9 pr-4 py-2 text-xs rounded bg-zinc-950 border border-zinc-700 text-zinc-100 placeholder-zinc-500 focus:outline-none focus:ring-2 focus:ring-zinc-100"
            />
          </div>

          <select
            id="status-filter"
            aria-label="Filter by status"
            value={statusFilter}
            onChange={(e) => setStatusFilter(e.target.value as 'ALL' | TicketStatus)}
            className="px-3 py-2 text-xs rounded bg-zinc-950 border border-zinc-700 text-zinc-100 focus:outline-none focus:ring-2 focus:ring-zinc-100"
          >
            <option value="ALL">All Statuses</option>
            <option value="Issued">Issued (Active)</option>
            <option value="Validated">Validated (Redeemed)</option>
            <option value="Revoked">Revoked (Voided)</option>
          </select>
        </div>
      </div>

      {/* Empty State requirement: "If a list or search result is empty, do not show a blank screen. Display a user-friendly 'No data found' message." */}
      {filteredTickets.length === 0 ? (
        <div
          role="region"
          aria-label="Empty search result"
          className="flex flex-col items-center justify-center p-12 bg-zinc-900/60 border border-dashed border-zinc-800 rounded-lg text-center"
        >
          <div className="p-3 bg-zinc-800 rounded-full mb-3 text-zinc-400">
            <Inbox className="w-6 h-6" aria-hidden="true" />
          </div>
          <h3 className="text-sm font-semibold text-zinc-200">No data found</h3>
          <p className="text-xs text-zinc-400 mt-1 max-w-sm">
            {searchTerm || statusFilter !== 'ALL'
              ? 'No tickets matched your current search filters. Try clearing filters or checking spelling.'
              : 'No tickets have been generated in this session yet. Use the form above to issue a new digital pass.'}
          </p>
          {(searchTerm || statusFilter !== 'ALL') && (
            <button
              type="button"
              onClick={() => {
                setSearchTerm('')
                setStatusFilter('ALL')
              }}
              aria-label="Clear all active filters"
              className="mt-4 px-3 py-1.5 text-xs rounded bg-zinc-800 hover:bg-zinc-700 text-zinc-200 font-mono transition-colors"
            >
              Clear Filters
            </button>
          )}
        </div>
      ) : (
        <div className="grid grid-cols-1 lg:grid-cols-2 gap-4">
          {filteredTickets.map((ticket) => (
            <article
              key={ticket.id}
              aria-labelledby={`ticket-title-${ticket.id}`}
              className="bg-zinc-900 border border-zinc-800 rounded-lg p-6 flex flex-col justify-between hover:border-zinc-700 transition-colors"
            >
              <div className="flex items-start gap-4">
                {/* QR Code Preview */}
                <div className="flex-shrink-0 bg-white p-2 rounded border border-zinc-300">
                  <img
                    src={ticket.qrDataUrl}
                    alt={`QR code for ticket ${ticket.ticketNumber}`}
                    className="w-24 h-24 object-contain"
                  />
                </div>

                {/* Ticket Details */}
                <div className="flex-1 min-w-0">
                  <div className="flex items-center gap-2 flex-wrap mb-1">
                    <span className="font-mono text-xs font-semibold px-2 py-0.5 rounded bg-zinc-800 border border-zinc-700 text-zinc-100">
                      {ticket.ticketNumber}
                    </span>
                    <span
                      className={`text-[10px] font-mono uppercase px-2 py-0.5 rounded border ${
                        ticket.status === 'Validated'
                          ? 'bg-zinc-800 border-zinc-600 text-zinc-100'
                          : ticket.status === 'Revoked'
                          ? 'bg-zinc-950 border-red-800 text-red-300'
                          : 'bg-zinc-950 border-zinc-700 text-zinc-300'
                      }`}
                    >
                      {ticket.status}
                    </span>
                    {ticket.isOfflineCreated && (
                      <span className="text-[10px] font-mono px-1.5 py-0.2 rounded bg-zinc-800 text-zinc-400 border border-zinc-700">
                        Offline Cache
                      </span>
                    )}
                  </div>

                  <h3
                    id={`ticket-title-${ticket.id}`}
                    className="text-sm font-semibold text-zinc-100 truncate"
                  >
                    {ticket.attendeeName}
                  </h3>
                  <p className="text-xs text-zinc-400 truncate">{ticket.attendeeEmail}</p>

                  <div className="mt-2 text-xs text-zinc-400 space-y-0.5">
                    <p>
                      <span className="text-zinc-400">Tier:</span>{' '}
                      <span className="text-zinc-200 font-medium">{ticket.ticketType}</span>
                    </p>
                    {ticket.attendeePhone && (
                      <p>
                        <span className="text-zinc-400">Phone:</span>{' '}
                        <span className="text-zinc-300 font-mono">{ticket.attendeePhone}</span>
                      </p>
                    )}
                    {ticket.notes && (
                      <p className="italic text-zinc-400 text-[11px] truncate">
                        "{ticket.notes}"
                      </p>
                    )}
                  </div>
                </div>
              </div>

              {/* Action Buttons */}
              <div className="flex items-center justify-between gap-2 mt-4 pt-4 border-t border-zinc-800 flex-wrap">
                <span className="text-[10px] font-mono text-zinc-400">
                  {new Date(ticket.issuedAt).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })}
                </span>

                <div className="flex items-center gap-2">
                  <button
                    type="button"
                    onClick={() => onPrintTicket(ticket)}
                    aria-label={`Print ticket ${ticket.ticketNumber}`}
                    className="flex items-center gap-1.5 px-2.5 py-1 text-xs rounded bg-zinc-800 hover:bg-zinc-700 text-zinc-200 transition-colors"
                  >
                    <Printer className="w-3.5 h-3.5" aria-hidden="true" />
                    <span>Print</span>
                  </button>

                  <a
                    href={ticket.qrDataUrl}
                    download={`${ticket.ticketNumber}-qr.png`}
                    aria-label={`Download QR image for ticket ${ticket.ticketNumber}`}
                    className="flex items-center gap-1.5 px-2.5 py-1 text-xs rounded bg-zinc-800 hover:bg-zinc-700 text-zinc-200 transition-colors"
                  >
                    <Download className="w-3.5 h-3.5" aria-hidden="true" />
                    <span>Save</span>
                  </a>

                  {ticket.status === 'Issued' && (
                    <button
                      type="button"
                      onClick={() => onVerifyTicket(ticket.id)}
                      aria-label={`Validate and redeem ticket ${ticket.ticketNumber}`}
                      className="flex items-center gap-1.5 px-2.5 py-1 text-xs rounded bg-zinc-100 text-zinc-950 font-semibold hover:bg-white transition-colors"
                    >
                      <CheckCircle2 className="w-3.5 h-3.5 text-zinc-950" aria-hidden="true" />
                      <span>Check-In</span>
                    </button>
                  )}

                  {ticket.status === 'Issued' && (
                    <button
                      type="button"
                      onClick={() => onRevokeTicket(ticket.id)}
                      aria-label={`Revoke ticket ${ticket.ticketNumber}`}
                      className="flex items-center gap-1.5 px-2 py-1 text-xs rounded border border-zinc-700 hover:border-red-600 hover:text-red-400 text-zinc-400 transition-colors"
                    >
                      <XCircle className="w-3.5 h-3.5" aria-hidden="true" />
                      <span>Revoke</span>
                    </button>
                  )}
                </div>
              </div>
            </article>
          ))}
        </div>
      )}
    </section>
  )
}
